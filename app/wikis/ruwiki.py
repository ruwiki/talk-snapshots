"""Русская Википедия: КУ — одна страница на день, номинации секциями `==`.

Групповые номинации перечисляют статьи подсекциями `=== [[Статья]] ===`,
итог — подсекцией «Итог» (у отдельной статьи или общий «По всем»).
Формального голосования нет: маркеры встречаются, но редко.
"""

from ..core.listing import DayPage
from ..core.outcome import OutcomeSection
from ..core.pages import HeadingLinks, Subsections, TitleFromHeading
from ..core.spec import Locale, ReasonClass, WikiSpec
from ..core.stance import VoteWords

MONTHS = {
    "января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6,
    "июля": 7, "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12,
}

WIKI = WikiSpec(
    dbname="ruwiki",
    host="ru.wikipedia.org",
    lang="ru",
    locale=Locale(
        months=MONTHS,
        user_prefixes=(
            "Участник", "Участница", "У", "Обсуждение участника", "Обсуждение участницы",
            "ОУ", "User", "User talk",
        ),
        contrib_prefixes=("Служебная:Вклад", "Special:Contributions", "Служебная:Contributions"),
        namespaces={
            "Википедия": 4, "ВП": 4, "Проект": 104, "Обсуждение": 1, "Участник": 2, "Участница": 2,
            "Категория": 14, "Шаблон": 10, "Файл": 6, "Портал": 100, "Модуль": 828,
            "Инкубатор": 102, "Справка": 12, "Обсуждение проекта": 105, "Обсуждение шаблона": 11,
            "Обсуждение категории": 15, "Обсуждение файла": 7, "Обсуждение Википедии": 5,
            "Обсуждение участника": 3, "Обсуждение участницы": 3, "Wikipedia": 4, "Category": 14,
            "Template": 10, "File": 6, "Talk": 1, "User": 2,
        },
        known_bots=frozenset({"QBA-II-bot", "KrBot", "BotDR", "Bot", "ClaymoreBot", "MBHbot"}),
        noise_patterns=(
            r"ruwiki-previous\w*",          # уведомления бота о прошлых номинациях и тёзках
            r"\{\{Автоперенос с КБУ",
            r"Автоматический перенос статьи с быстрого удаления",
        ),
        boilerplate_patterns=(
            r"\{\{КУ-Навигация\}\}",
            r"\{\{(?:subst:)?Пропущенный итог[^}]*\}\}",
        ),
    ),
    listing=DayPage("Википедия:К удалению/{d} {month} {yyyy}", nomination_level=2),
    pages=(Subsections(), HeadingLinks(), TitleFromHeading()),
    outcome=OutcomeSection(
        section_names=("Итог", "Автоитог", "Предварительный итог", "Оспоренный итог"),
        kinds={
            r"удален[оаы]?\b|удалить\b|быстро удалено": "delete",
            r"оставлен[оаы]?\b|оставить\b|оставляем": "keep",
            r"переименован[оаы]?\b|переименовать": "rename",
            r"объединен[оаы]?\b|объединить": "merge",
            r"перенаправлен[оаы]?\b|редирект|перенаправление": "redirect",
            r"перенес[её]н[оаы]?\b|в инкубатор|переношу": "moved",
            r"номинация снята|снято\b|снята\b|снимаю": "withdrawn",
        },
    ),
    stance=VoteWords(("За", "Против", "Оставить", "Удалить", "Переименовать", "Объединить")),
    # «{{к удалению|…}}» в комментарии = MediaWiki подставила начало страницы: удаление пачкой по итогу без причины
    reason=ReasonClass(discussion=r"К удалению/|\{\{к удалению\||по итогу|согласно итогу", speedy=r"КБУ#([А-Я]\d+)"),
    common_headings=("По всем", "По всем статьям", "Общее", "По обеим"),
    label="Русская Википедия — КУ",
)
